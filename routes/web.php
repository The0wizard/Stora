//Home Page
// Homepage route that uses the home method in BookController
Route::get('/', [BookController::class, 'home'])->name('home');

// Admin or User after login & prevent user from accessing admin dashboard
Route::get('/admin/dashboard', function () {
    if (Auth::user()->role === 'admin') {
        return view('layouts.admin');
    } else {
        return redirect()->route('home'); // or route to user home page
    }
})->name('admin.dashboard');

Route::get('/dashboard', function () {
    if (Auth::user()->role === 'admin') {
        return view('layouts.admin');
    } else {
        return redirect()->route('home'); // or route to user home page
    }
})
    ->middleware(['auth', 'verified'])
    ->name('dashboard');

Route::get('/redirect-after-login', function () {
    if (Auth::user()->role === 'admin') {
        return redirect()->route('layouts.admin');
    }

    return redirect()->route('home'); // or route to user home page
});

